// @vitest-environment node
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { CaptureAuthority } from './capture-authority'
import type { CaptureReservation } from './cloud-sync'

const user = '11111111-1111-4111-8111-111111111111'
function reservation(seconds = 120): CaptureReservation {
  return { reservation_id: 'lease-1', user_id: user, max_duration_sec: seconds, expires_at: new Date(Date.now() + 600_000).toISOString() }
}
function fixture() {
  let owner: string | null = user
  const reserve = vi.fn(async () => reservation())
  const start = vi.fn(async (lease: CaptureReservation) => ({ ...lease, expires_at: new Date(Date.now() + lease.max_duration_sec * 1000).toISOString() }))
  const finish = vi.fn(async () => {})
  const stop = vi.fn()
  const gate = new CaptureAuthority({ userId: () => owner, reserve, start, finish, stop })
  return { gate, reserve, start, finish, stop, owner: (next: string | null) => { owner = next } }
}
const request = (command = 'start_capture') => ({ id: 'request-1', command, payload: { auto_stop_after_sec: 99999, serial: 'phone' } })
beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(new Date('2026-10-22T03:00:00Z')) })
afterEach(() => vi.useRealTimers())

describe('main-process measurement authorization', () => {
  it('gates local memory QA on a signed-in desktop without reserving time', async () => {
    const f = fixture()
    for (const command of ['play_memory_qa_sample', 'play_memory_qa_summary']) {
      f.owner(null)
      await expect(f.gate.authorize(request(command), 1)).rejects.toThrow('auth-required')
      f.owner(user)
      await expect(f.gate.authorize(request(command), 1)).resolves.toMatchObject({command})
    }
    expect(f.reserve).not.toHaveBeenCalled()
  })
  it('excludes backend-confirmed pauses from the watchdog without reserving more quota', async () => {
    const f = fixture()
    await f.gate.authorize(request(), 1)
    f.gate.consume({ id: 'request-1', ok: true, result: { capture_id: 'c' } })
    f.gate.consume({ event: 'snapshot', capture_id: 'c' })
    await vi.advanceTimersByTimeAsync(10_000)
    await expect(f.gate.authorize({ id: 'pause', command: 'pause_capture', payload: { capture_id: 'c' } }, 2)).rejects.toThrow('auth-required')
    await expect(f.gate.authorize({ id: 'pause', command: 'pause_capture', payload: { capture_id: 'c' } }, 1)).resolves.toMatchObject({ command: 'pause_capture' })
    f.gate.consume({ event: 'capture_state', capture_id: 'c', paused: true })
    await vi.advanceTimersByTimeAsync(180_000)
    f.gate.consume({ event: 'capture_state', capture_id: 'c', paused: true })
    expect(f.stop).not.toHaveBeenCalled()
    f.gate.consume({ event: 'capture_state', capture_id: 'c', paused: false })
    f.gate.consume({ event: 'capture_state', capture_id: 'c', paused: false })
    await vi.advanceTimersByTimeAsync(109_999)
    expect(f.stop).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(1)
    expect(f.stop).toHaveBeenCalledWith('stop_capture', 'c')
    expect(f.reserve).toHaveBeenCalledTimes(1)
    expect(f.finish).toHaveBeenCalledTimes(1)
  })

  it('honors a pause while server activation is pending and still revokes a paused capture', async () => {
    const f = fixture()
    let resolve!: (lease: CaptureReservation) => void
    f.start.mockImplementationOnce(() => new Promise(done => { resolve = done }))
    await f.gate.authorize(request(), 1)
    f.gate.consume({ id: 'request-1', ok: true, result: { capture_id: 'c' } })
    f.gate.consume({ event: 'snapshot', capture_id: 'c' })
    await vi.advanceTimersByTimeAsync(0)
    f.gate.consume({ event: 'capture_state', capture_id: 'c', paused: true })
    resolve({ ...reservation(), expires_at: new Date(Date.now() + 120_000).toISOString() })
    await vi.advanceTimersByTimeAsync(180_000)
    expect(f.stop).not.toHaveBeenCalled()
    f.gate.revoke()
    expect(f.stop).toHaveBeenCalledWith('stop_capture', 'c')
    await vi.advanceTimersByTimeAsync(0)
    expect(f.finish).toHaveBeenCalledTimes(1)
    f.owner(null)
    await expect(f.gate.authorize({ id: 'resume', command: 'resume_capture', payload: { capture_id: 'c' } }, 1)).rejects.toThrow('auth-required')
  })
  it('requires authenticated ownership for starts and guards, but always permits stop/save recovery', async () => {
    const f = fixture(); f.owner(null)
    for (const command of ['start_capture', 'create_temperature_guard', 'create_temperature_preview', 'companion_metrics']) {
      await expect(f.gate.authorize(request(command), 1)).rejects.toThrow('auth-required')
    }
    await expect(f.gate.authorize(request('stop_capture'), 1)).resolves.toMatchObject({ command: 'stop_capture' })
    await expect(f.gate.authorize(request('auto_save_raw_csv'), 1)).resolves.toMatchObject({ command: 'auto_save_raw_csv' })
    expect(f.reserve).not.toHaveBeenCalled()
  })
  it('reserves server quota and clamps a forged renderer timer', async () => {
    const f = fixture()
    const allowed = await f.gate.authorize(request(), 1)
    expect(f.reserve).toHaveBeenCalledWith(expect.any(String), 3600)
    expect(allowed.payload.auto_stop_after_sec).toBe(120)
    f.gate.dispatched(allowed.id, 'no-process')
    await Promise.resolve()
    expect(f.finish).toHaveBeenCalledWith(expect.any(Object), 'cancelled')
  })
  it('fails closed on server failure and cancels a response arriving after account change', async () => {
    const f = fixture()
    f.reserve.mockRejectedValueOnce(new Error('quota-unavailable'))
    await expect(f.gate.authorize(request(), 1)).rejects.toThrow('quota-unavailable')
    let resolve!: (v: CaptureReservation) => void
    f.reserve.mockImplementationOnce(() => new Promise(r => { resolve = r }))
    const pending = f.gate.authorize(request(), 1)
    f.gate.revoke(); f.owner('other')
    resolve(reservation())
    await expect(pending).rejects.toThrow('auth-required')
    expect(f.finish).toHaveBeenCalledWith(expect.any(Object), 'cancelled')
  })
  it('does not bill handshake or temperature wait; activates once on the first actual sample', async () => {
    const f = fixture()
    await f.gate.authorize(request('create_temperature_guard'), 1)
    f.gate.consume({ id: 'request-1', ok: true, result: { guard_id: 'g' } })
    await vi.advanceTimersByTimeAsync(120_000)
    expect(f.start).not.toHaveBeenCalled()
    f.gate.consume({ event: 'temperature_guard_started', guard_id: 'g', capture_id: 'c' })
    expect(f.start).not.toHaveBeenCalled()
    f.gate.consume({ event: 'snapshot', capture_id: 'c' })
    f.gate.consume({ event: 'snapshot', capture_id: 'c' })
    await Promise.resolve()
    expect(f.start).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(120_000)
    expect(f.stop).toHaveBeenCalledWith('stop_capture', 'c')
    expect(f.finish).toHaveBeenCalledTimes(1)
  })
  it.each(['rejection', 'synchronous failure'])('stops a capture on activation %s and preserves idempotent finish', async (failure) => {
    const f = fixture()
    if (failure === 'rejection') f.start.mockRejectedValueOnce(new Error('network'))
    else f.start.mockImplementationOnce(() => { throw new Error('network') })
    await f.gate.authorize(request(), 1)
    f.gate.consume({ id: 'request-1', ok: true, result: { capture_id: 'c' } })
    f.gate.consume({ event: 'snapshot', capture_id: 'c' })
    await vi.advanceTimersByTimeAsync(0)
    f.gate.consume({ event: 'capture_ended', capture_id: 'c' })
    expect(f.stop).toHaveBeenCalledWith('stop_capture', 'c')
    expect(f.finish).toHaveBeenCalledTimes(1)
  })
  it('handles a sample and end event arriving before the start response', async () => {
    const f = fixture()
    await f.gate.authorize(request(), 1)
    f.gate.consume({ event: 'snapshot', capture_id: 'c' })
    f.gate.consume({ event: 'capture_ended', capture_id: 'c' })
    f.gate.consume({ id: 'request-1', ok: true, result: { capture_id: 'c' } })
    await vi.advanceTimersByTimeAsync(0)
    expect(f.start).toHaveBeenCalledTimes(1)
    expect(f.finish).toHaveBeenCalledWith(expect.any(Object), 'completed')
  })
  it('rejects a guard activation from another window and expires an unused hold', async () => {
    const f = fixture()
    await f.gate.authorize(request('create_temperature_guard'), 1)
    f.gate.consume({ id: 'request-1', ok: true, result: { guard_id: 'g' } })
    await expect(f.gate.authorize({ id: 'activate', command: 'activate_temperature_guard', payload: { guard_id: 'g' } }, 2)).rejects.toThrow('auth-required')
    await vi.advanceTimersByTimeAsync(600_000)
    expect(f.start).not.toHaveBeenCalled()
    expect(f.stop).toHaveBeenCalledWith('stop_temperature_guard', 'g')
    expect(f.finish).toHaveBeenCalledWith(expect.any(Object), 'cancelled')
  })
  it('links a guard promotion and sample arriving before its creation response', async () => {
    const f = fixture()
    await f.gate.authorize(request('create_temperature_guard'), 1)
    f.gate.consume({ event: 'temperature_guard_started', guard_id: 'g', capture_id: 'c' })
    f.gate.consume({ event: 'snapshot', capture_id: 'c' })
    f.gate.consume({ event: 'capture_ended', capture_id: 'c' })
    f.gate.consume({ id: 'request-1', ok: true, result: { guard_id: 'g' } })
    await vi.advanceTimersByTimeAsync(0)
    expect(f.start).toHaveBeenCalledTimes(1)
    expect(f.finish).toHaveBeenCalledWith(expect.any(Object), 'completed')
  })
  it('stops a promoted capture that arrives after revocation and before the guard response', async () => {
    const f = fixture()
    await f.gate.authorize(request('create_temperature_guard'), 1)
    f.gate.revoke()
    f.gate.consume({ event: 'temperature_guard_started', guard_id: 'g', capture_id: 'late-c' })
    f.gate.consume({ id: 'request-1', ok: true, result: { guard_id: 'g' } })
    expect(f.stop).toHaveBeenCalledWith('stop_capture', 'late-c')
    expect(f.start).not.toHaveBeenCalled()
  })
  it('stops a late promotion of a known guard after its reservation was finished', async () => {
    const f = fixture()
    await f.gate.authorize(request('create_temperature_guard'), 1)
    f.gate.consume({ id: 'request-1', ok: true, result: { guard_id: 'g' } })
    f.gate.revoke()
    f.gate.consume({ event: 'temperature_guard_started', guard_id: 'g', capture_id: 'late-c' })
    expect(f.stop).toHaveBeenCalledWith('stop_capture', 'late-c')
    expect(f.start).not.toHaveBeenCalled()
  })
  it('stops late resources after logout and rejects reservations for a closed window', async () => {
    const f = fixture()
    await f.gate.authorize(request(), 1)
    f.gate.revoke()
    f.gate.consume({ id: 'request-1', ok: true, result: { capture_id: 'late' } })
    expect(f.stop).toHaveBeenCalledWith('stop_capture', 'late')
    f.gate.closeOwner(1)
    await expect(f.gate.authorize(request(), 1)).rejects.toThrow('auth-required')
  })
})
