from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional, Tuple


class Platform(str, Enum):
    ANDROID = "android"
    IOS = "ios"


@dataclass
class DeviceInfo:
    serial: str
    platform: Platform
    model: str = "unknown"
    os_version: str = "unknown"
    connection_type: str = "usb"
    code_name: str = ""   # ro.product.device — internal codename (e.g. "a53x")
    hw_ver: str = ""      # ro.product.board — board name (e.g. "atlantic")
    sw_ver: str = ""      # last 4 chars of ro.build.display.id (e.g. "CWA1")
    # Real hardware serial (ro.serialno) for display. ``serial`` stays the adb
    # transport id, which for a wireless device is the "ip:port" address — not a
    # real serial. Populated only when they differ (wireless); "" means use
    # ``serial`` for display. iOS leaves this empty (its UDID is already real).
    hw_serial: str = ""
    # User-assigned name. ``model`` is the hardware model's readable name where
    # known; the raw Apple ProductType is preserved in ``model_identifier``.
    display_name: str = ""
    # Complete OS/firmware identifiers, separate from the marketing OS version.
    build_version: str = ""
    build_name: str = ""
    # Apple ProductType (e.g. iPhone15,2) and observed regulatory A-number.
    # Neither is a device-specific serial; never derive a regional A-number.
    model_identifier: str = ""
    model_number: str = ""
    android_memory_form_factor: Optional[str] = None
    android_sdk_int: Optional[int] = None


@dataclass
class PackageInfo:
    bundle_id: str
    label: Optional[str] = None
    version_name: Optional[str] = None
    version_code: Optional[str] = None
    apk_path: Optional[str] = None
    uid: Optional[str] = None


@dataclass(frozen=True)
class BatteryTemperatureReading:
    """One numeric battery-pack temperature sample.

    ``sampled_at`` is an ISO-8601 timestamp generated by the platform monitor
    at read time.  ``source`` is deliberately explicit because both Android
    and iOS have a fallback ladder and the UI/export path must never mistake a
    charger, CPU, or skin sensor for the battery pack.
    """

    temperature_c: float
    sampled_at: str
    source: str


@dataclass(frozen=True)
class TemperatureGuardConfig:
    """Immutable target captured when a temperature guard is created."""

    platform: Platform
    device: DeviceInfo
    package: PackageInfo
    threshold_c: float
    required_hits: int = 2
    cold_start: bool = True
    duration_sec: float = 1.0
    # Optional live-capture deadline.  The API arms it only after the first
    # snapshot has actually been emitted, so guard/preflight time never counts
    # against the requested measurement time.
    auto_stop_after_sec: Optional[float] = None
    # Optional on-device HUD request, ``{"enabled": bool, "metrics": [...]}``.
    # Carried here because the guard promotes into a capture on its own thread,
    # long after the payload that asked for the overlay was parsed.
    overlay: Optional[Dict[str, Any]] = None


@dataclass
class FrameStats:
    total_frames: int = 0
    janky_frames: int = 0
    # janky_frames split by severity: small_jank + big_jank == janky_frames when
    # a per-frame/histogram source is available (0 when only an aggregate count is).
    small_jank: int = 0
    big_jank: int = 0
    jank_percent: float = 0.0
    p50_ms: float = 0.0
    p90_ms: float = 0.0
    p95_ms: float = 0.0
    p99_ms: float = 0.0
    missed_vsync: int = 0
    slow_ui_thread: int = 0
    frame_deadline_missed: int = 0
    fps_estimate: Optional[float] = None
    source: Optional[str] = None
    scope: Optional[str] = None
    experimental: bool = False
    # Observed events only; aggregate FPS never manufactures frame durations.
    raw_events: List[Dict[str, Any]] = field(default_factory=list)
    raw_events_dropped: int = 0


@dataclass
class MemStats:
    pss_total_kb: Optional[int] = 0
    rss_total_kb: Optional[int] = 0
    memory_source: Optional[str] = None
    anon_rss_kib: Optional[int] = None
    swap_kib: Optional[int] = None
    anon_rss_plus_swap_kib: Optional[int] = None
    play_memory_state: Optional[str] = None
    play_memory_state_source: Optional[str] = None
    play_memory_category: Optional[str] = None
    play_memory_category_source: Optional[str] = None
    play_memory_ram_kib: Optional[int] = None
    play_memory_sdk_int: Optional[int] = None
    play_memory_form_factor: Optional[str] = None
    play_memory_pid: Optional[int] = None
    play_memory_start_ticks: Optional[int] = None
    java_heap_kb: int = 0
    native_heap_kb: int = 0
    graphics_kb: int = 0
    code_kb: int = 0
    stack_kb: int = 0
    # System-wide RAM (0 when unavailable). sys_used_kb = MemTotal - MemAvailable.
    sys_total_kb: int = 0
    sys_used_kb: int = 0


@dataclass
class CpuStats:
    pid: int = 0
    # Raw app/process CPU where 100% means one fully busy logical CPU. It may
    # exceed 100% on a multi-core device. Missing/unreadable values stay None.
    cpu_percent: Optional[float] = None
    mem_percent: float = 0.0
    # System-wide CPU% across all cores (None when the collector cannot supply it).
    total_percent: Optional[float] = None
    per_core_freq_mhz: List[float] = field(default_factory=list)
    # Collector-provided app normalization, 0–100. Android applies
    #   min(100, app% / cores) * (Σ current core freq / Σ max core freq)
    # and leaves the value unavailable when clock evidence is incomplete. iOS
    # has no per-core clock stream and uses app% / logical cores only.
    cpu_norm: Optional[float] = None
    per_core_percent: List[Optional[float]] = field(default_factory=list)
    logical_core_count: Optional[int] = None
    total_source: Optional[str] = None
    total_status: Optional[str] = None


@dataclass
class NetworkStats:
    """Device-wide network counters and rates for one capture sample.

    Counters are read from the non-loopback interfaces in ``/proc/net/dev``.
    They are intentionally device-wide: Android does not expose reliable
    per-UID counters to adb on production builds. Rates are ``None`` until a
    second monotonic counter sample establishes a trustworthy delta.
    """

    rx_bytes: Optional[int] = None
    tx_bytes: Optional[int] = None
    rx_kbps: Optional[float] = None
    tx_kbps: Optional[float] = None


@dataclass
class GpuStats:
    busy_percent: Optional[float] = None
    clock_mhz: Optional[float] = None
    temp_c: Optional[float] = None


@dataclass
class ThermalStats:
    zones_c: Dict[str, float] = field(default_factory=dict)


@dataclass
class BatteryStats:
    level_percent: Optional[int] = None
    current_ma: Optional[float] = None
    status: Optional[str] = None
    voltage_mv: Optional[float] = None


@dataclass
class MetricsSnapshot:
    device: DeviceInfo
    package: PackageInfo
    captured_at: str
    duration_sec: float
    frames: FrameStats = field(default_factory=FrameStats)
    memory: MemStats = field(default_factory=MemStats)
    cpu: CpuStats = field(default_factory=CpuStats)
    network: NetworkStats = field(default_factory=NetworkStats)
    gpu: GpuStats = field(default_factory=GpuStats)
    thermal: ThermalStats = field(default_factory=ThermalStats)
    battery: BatteryStats = field(default_factory=BatteryStats)
    raw: Dict[str, Any] = field(default_factory=dict)
    # Freshness is measured from the source event, not repeated sample emission.
    metric_status: Dict[str, Dict[str, Any]] = field(default_factory=dict)
    # Active measurement time; excludes user pauses. Legacy snapshots omit it.
    elapsed_sec: Optional[float] = None
    # Sticky collector evidence: resuming never makes this capture eligible again.
    pause_used: bool = False


# --- Aggregated report summaries for live capture and CSV replay ---


@dataclass
class FpsStats:
    """Session-level FPS statistics from a live capture report."""

    median: float = 0.0
    average: float = 0.0
    median_stability: float = 0.0
    average_stability: float = 0.0
    first_half: float = 0.0
    first_half_stability: float = 0.0
    second_half: float = 0.0
    second_half_stability: float = 0.0
    max_fps: float = 0.0
    fps_std: float = 0.0
    fps_below_90pct_ratio: float = 0.0
    norm_fps_std: Optional[float] = None
    norm_fps_avg: Optional[float] = None
    norm_fps_max: Optional[float] = None


@dataclass
class ThermalSummary:
    """Live-capture temperature zones mapped to (start_c, end_c, max_c)."""

    zones: Dict[str, Tuple[float, float, float]] = field(default_factory=dict)


@dataclass
class ReportSummary:
    """Aggregated session summary that does not fit MetricsSnapshot's per-sample model.

    A loaded live CSV produces one ReportSummary plus (optionally) a
    list[MetricsSnapshot] reconstructed from its fps_series.
    """

    file_path: str
    source: str  # "live_csv"
    duration_min: int = 0
    duration_sec: int = 0
    fps: Optional[FpsStats] = None
    thermal: Optional[ThermalSummary] = None
    cpu_usage_avg: Optional[float] = None
    gpu_usage_avg: Optional[float] = None
    power_mw_avg: Optional[float] = None
    abs_time_start: Optional[str] = None
    abs_time_end: Optional[str] = None
    metadata: Dict[str, str] = field(default_factory=dict)
